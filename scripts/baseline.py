"""Compare ruff and mypy findings to the committed baselines.

The configs in pyproject.toml are strict. Findings that already exist are
listed under scripts/baselines/ so the current tree passes. A new finding
fails the check. A finding that disappeared fails too, so the debt list
cannot drift silently. Regenerate only on purpose with `make baseline`.
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

# Running `python scripts/baseline.py` puts scripts/ on sys.path, not the
# repo root, so the package import below would fail. Put the root on the
# path first when this file is the entry point. `python -m scripts.baseline`
# already has a package context and skips this.
if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import json
import re

from scripts.which_tool import run_tool, which_tool

ROOT = Path(__file__).resolve().parent.parent
BASELINES = ROOT / "scripts" / "baselines"

# One diagnostic per line. Notes and summaries are ignored; an error line that
# does not match is a hard failure so a mypy format change cannot hide findings.
MYPY_ERROR = re.compile(
    r"^(?P<path>.+?):(?P<line>\d+):(?P<col>\d+): error: "
    r"(?P<message>.*?)(?: \[(?P<code>[A-Za-z0-9-]+)\])?$"
)

_HEADER = (
    "# Generated by `make baseline`. Do not edit by hand.\n"
    "# COUNT<TAB>PATH<TAB>CODE<TAB>MESSAGE\n"
    "# A count that does not match the tree fails make lint or make typecheck.\n"
)


def fingerprint(path: str, code: str, message: str) -> str:
    """Stable id for one finding. Line numbers are omitted so edits above it do not churn."""
    clean = " ".join(message.replace("\t", " ").split())
    return f"{path}\t{code}\t{clean}"


def rel_path(filename: str) -> str:
    path = Path(filename)
    if path.is_absolute():
        try:
            return path.resolve().relative_to(ROOT).as_posix()
        except ValueError:
            return path.as_posix()
    return path.as_posix()


def parse_ruff(stdout: str) -> Counter[str]:
    raw = _json_value(stdout or "[]")
    if not isinstance(raw, list):
        raise RuntimeError("ruff did not return a JSON list")
    counts: Counter[str] = Counter()
    for item in raw:
        record = _string_dict(item)
        filename = record.get("filename")
        code = record.get("code")
        message = record.get("message")
        if not isinstance(filename, str) or not isinstance(code, str) or not isinstance(message, str):
            raise RuntimeError("ruff diagnostic missing filename, code, or message")
        counts[fingerprint(rel_path(filename), code, message)] += 1
    return counts


def _json_value(text: str) -> object:
    # json.loads is typed as Any. The annotation is what the rest of the parser sees.
    value: object = json.loads(text)
    return value


def _string_dict(value: object) -> dict[str, object]:
    if not isinstance(value, dict):
        raise RuntimeError("ruff diagnostic was not an object")
    out: dict[str, object] = {}
    for key, inner in value.items():
        if not isinstance(key, str):
            raise RuntimeError("ruff diagnostic had a non-string key")
        out[key] = inner
    return out


def parse_mypy(stdout: str) -> Counter[str]:
    counts: Counter[str] = Counter()
    for lineno, raw in enumerate(stdout.splitlines(), 1):
        if not raw.strip():
            continue
        match = MYPY_ERROR.match(raw)
        if match is None:
            if ": error:" in raw:
                raise RuntimeError(f"unparsed mypy error line {lineno}: {raw}")
            continue
        code = match.group("code") or "unknown"
        counts[fingerprint(rel_path(match.group("path")), code, match.group("message"))] += 1
    return counts


def collect_ruff() -> Counter[str]:
    proc = run_tool([which_tool("ruff"), "check", "--output-format", "json", "."])
    if proc.returncode not in (0, 1):
        detail = proc.stderr.strip() or proc.stdout.strip() or "ruff failed"
        raise RuntimeError(detail)
    return parse_ruff(proc.stdout)


def collect_mypy() -> Counter[str]:
    proc = run_tool(
        [
            which_tool("mypy"),
            "--no-error-summary",
            "--no-pretty",
            "--show-column-numbers",
            "--hide-error-context",
            "--no-color-output",
            "--show-error-codes",
        ]
    )
    if proc.returncode not in (0, 1):
        detail = proc.stderr.strip() or proc.stdout.strip() or "mypy failed"
        raise RuntimeError(detail)
    # mypy writes diagnostics to stdout. stderr is reserved for crashes.
    if proc.returncode == 1 and not proc.stdout.strip() and proc.stderr.strip():
        raise RuntimeError(proc.stderr.strip())
    return parse_mypy(proc.stdout)


def render(counts: Counter[str]) -> str:
    rows = "\n".join(f"{counts[key]}\t{key}" for key in sorted(counts))
    if rows:
        return f"{_HEADER}{rows}\n"
    return _HEADER


def load_counts(path: Path) -> Counter[str]:
    if not path.is_file():
        raise ValueError(f"missing baseline {path}")
    counts: Counter[str] = Counter()
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not raw.strip() or raw.startswith("#"):
            continue
        count_text, key = _split_baseline_line(path, lineno, raw)
        counts[key] += int(count_text)
    return counts


def _split_baseline_line(path: Path, lineno: int, raw: str) -> tuple[str, str]:
    parts = raw.split("\t")
    if len(parts) != 4:
        raise ValueError(f"{path}:{lineno}: expected COUNT, PATH, CODE, MESSAGE")
    count_text, path_text, code, message = parts
    if not count_text.isdigit() or int(count_text) < 1:
        raise ValueError(f"{path}:{lineno}: count must be a positive integer")
    return count_text, f"{path_text}\t{code}\t{message}"


def diff_counts(current: Counter[str], baseline: Counter[str]) -> tuple[list[str], list[str]]:
    """Return (added, removed) lines. Added means the tree has more than the baseline."""
    added: list[str] = []
    removed: list[str] = []
    for key in sorted(set(current) | set(baseline)):
        delta = current.get(key, 0) - baseline.get(key, 0)
        if delta > 0:
            added.append(f"+{delta} {key}")
        elif delta < 0:
            removed.append(f"{delta} {key}")
    return added, removed


def _report(kind: str, added: list[str], removed: list[str]) -> int:
    if not added and not removed:
        print(f"{kind}: baseline matches")
        return 0
    print(f"{kind}: baseline drift", file=sys.stderr)
    for line in added:
        print(f"  new     {line}", file=sys.stderr)
    for line in removed:
        print(f"  stale   {line}", file=sys.stderr)
    print("Run `make baseline` only after accepting that change as debt.", file=sys.stderr)
    return 1


def _check(kind: str, current: Counter[str], path: Path) -> int:
    added, removed = diff_counts(current, load_counts(path))
    return _report(kind, added, removed)


def execute(command: str) -> int:
    ruff_path = BASELINES / "ruff.txt"
    mypy_path = BASELINES / "mypy.txt"
    want_ruff = command in {"check", "check-ruff", "update"}
    want_mypy = command in {"check", "check-mypy", "update"}
    ruff_counts: Counter[str] = collect_ruff() if want_ruff else Counter()
    mypy_counts: Counter[str] = collect_mypy() if want_mypy else Counter()
    if command == "update":
        BASELINES.mkdir(parents=True, exist_ok=True)
        ruff_path.write_text(render(ruff_counts), encoding="utf-8")
        mypy_path.write_text(render(mypy_counts), encoding="utf-8")
        print(f"wrote {ruff_path.relative_to(ROOT)} ({sum(ruff_counts.values())})")
        print(f"wrote {mypy_path.relative_to(ROOT)} ({sum(mypy_counts.values())})")
        return 0
    status = 0
    if want_ruff:
        status = max(status, _check("ruff", ruff_counts, ruff_path))
    if want_mypy:
        status = max(status, _check("mypy", mypy_counts, mypy_path))
    return status


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compare ruff and mypy output to committed baselines.")
    parser.add_argument("command", choices=("check", "check-ruff", "check-mypy", "update"))
    args = parser.parse_args(argv)
    command = args.command
    if not isinstance(command, str):
        print("baseline: missing command", file=sys.stderr)
        return 2
    try:
        return execute(command)
    except (ValueError, RuntimeError) as exc:
        print(f"baseline: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
